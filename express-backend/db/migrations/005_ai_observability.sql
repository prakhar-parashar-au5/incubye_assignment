-- Synthetic-data AI observability. Times are UTC, supplied by the application.
-- Turn-owned messages cascade with their trace; conversations survive turn deletion.
CREATE TABLE ai_conversations (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  hr_user_id INT UNSIGNED NOT NULL,
  created_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  KEY idx_ai_conversations_owner (hr_user_id, created_at),
  CONSTRAINT fk_ai_conversations_user FOREIGN KEY (hr_user_id) REFERENCES hr_users(id) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE ai_traces (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  conversation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  previous_trace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  hr_user_id INT UNSIGNED NOT NULL,
  sequence INT UNSIGNED NOT NULL,
  request_id VARCHAR(100) NOT NULL,
  idempotency_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
  command_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  status ENUM('STARTED','COMPLETED','FAILED') NOT NULL DEFAULT 'STARTED',
  failure_stage VARCHAR(40) NULL,
  error_category VARCHAR(80) NULL,
  model VARCHAR(120) NOT NULL,
  prompt_version VARCHAR(80) NOT NULL,
  prompt_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  user_content JSON NOT NULL,
  model_messages JSON NOT NULL,
  final_response JSON NULL,
  user_message_id BIGINT UNSIGNED NULL,
  final_message_id BIGINT UNSIGNED NULL,
  started_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  duration_ms INT UNSIGNED NULL,
  input_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  output_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  reasoning_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  model_call_count INT UNSIGNED NOT NULL DEFAULT 0,
  tool_call_count INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uk_ai_traces_conversation_sequence (conversation_id, sequence),
  UNIQUE KEY uk_ai_traces_idempotency (conversation_id, idempotency_key),
  KEY idx_ai_traces_started (started_at, id),
  KEY idx_ai_traces_actor (hr_user_id, started_at),
  KEY idx_ai_traces_status (status, started_at),
  KEY idx_ai_traces_model (model, started_at),
  KEY idx_ai_traces_error (error_category, started_at),
  KEY idx_ai_traces_previous (previous_trace_id),
  CONSTRAINT fk_ai_traces_conversation FOREIGN KEY (conversation_id) REFERENCES ai_conversations(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_ai_traces_user FOREIGN KEY (hr_user_id) REFERENCES hr_users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_ai_traces_previous FOREIGN KEY (previous_trace_id) REFERENCES ai_traces(id) ON UPDATE RESTRICT ON DELETE SET NULL,
  CONSTRAINT chk_ai_traces_duration CHECK (duration_ms IS NULL OR duration_ms >= 0),
  CONSTRAINT chk_ai_traces_status_time CHECK ((status = 'STARTED' AND completed_at IS NULL) OR (status <> 'STARTED' AND completed_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE ai_messages (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  conversation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  trace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  sequence INT UNSIGNED NOT NULL,
  role ENUM('USER','ASSISTANT') NOT NULL,
  content JSON NOT NULL,
  created_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_ai_messages_conversation_sequence (conversation_id, sequence),
  KEY idx_ai_messages_trace (trace_id),
  KEY idx_ai_messages_created (created_at),
  CONSTRAINT fk_ai_messages_conversation FOREIGN KEY (conversation_id) REFERENCES ai_conversations(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_ai_messages_trace FOREIGN KEY (trace_id) REFERENCES ai_traces(id) ON UPDATE RESTRICT ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE ai_model_calls (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  trace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sequence INT UNSIGNED NOT NULL,
  provider_request_id VARCHAR(120) NULL,
  provider VARCHAR(80) NOT NULL,
  model VARCHAR(120) NOT NULL,
  input_messages JSON NOT NULL,
  tool_schemas JSON NOT NULL,
  prompt_version VARCHAR(80) NOT NULL,
  prompt_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  output_content JSON NULL,
  tool_decisions JSON NULL,
  status ENUM('STARTED','SUCCEEDED','FAILED') NOT NULL DEFAULT 'STARTED',
  failure_category VARCHAR(80) NULL,
  safe_error JSON NULL,
  input_tokens INT UNSIGNED NULL,
  output_tokens INT UNSIGNED NULL,
  total_tokens INT UNSIGNED NULL,
  reasoning_tokens INT UNSIGNED NULL,
  started_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  latency_ms INT UNSIGNED NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_ai_model_calls_trace_sequence (trace_id, sequence),
  KEY idx_ai_model_calls_started (started_at),
  CONSTRAINT fk_ai_model_calls_trace FOREIGN KEY (trace_id) REFERENCES ai_traces(id) ON UPDATE RESTRICT ON DELETE CASCADE,
  CONSTRAINT chk_ai_model_calls_latency CHECK (latency_ms IS NULL OR latency_ms >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE ai_tool_calls (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  trace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  model_call_id BIGINT UNSIGNED NOT NULL,
  provider_tool_call_id VARCHAR(120) NULL,
  sequence INT UNSIGNED NOT NULL,
  tool_name VARCHAR(120) NOT NULL,
  requested_arguments JSON NOT NULL,
  validation_status ENUM('PENDING','VALID','REJECTED') NOT NULL DEFAULT 'PENDING',
  validation_errors JSON NULL,
  status ENUM('STARTED','REJECTED','SUCCEEDED','FAILED') NOT NULL DEFAULT 'STARTED',
  result JSON NULL,
  error_category VARCHAR(80) NULL,
  safe_error JSON NULL,
  started_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  duration_ms INT UNSIGNED NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_ai_tool_calls_trace_sequence (trace_id, sequence),
  KEY idx_ai_tool_name (tool_name, started_at),
  KEY idx_ai_tool_model (model_call_id),
  KEY idx_ai_tool_started (started_at),
  CONSTRAINT fk_ai_tool_calls_trace FOREIGN KEY (trace_id) REFERENCES ai_traces(id) ON UPDATE RESTRICT ON DELETE CASCADE,
  CONSTRAINT fk_ai_tool_calls_model FOREIGN KEY (model_call_id) REFERENCES ai_model_calls(id) ON UPDATE RESTRICT ON DELETE CASCADE,
  CONSTRAINT chk_ai_tool_calls_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE mcp_tool_calls (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_id VARCHAR(100) NOT NULL,
  hr_user_id INT UNSIGNED NOT NULL,
  tool_name VARCHAR(120) NOT NULL,
  requested_arguments JSON NOT NULL,
  validation_status ENUM('PENDING','VALID','REJECTED') NOT NULL DEFAULT 'PENDING',
  status ENUM('STARTED','REJECTED','SUCCEEDED','FAILED') NOT NULL DEFAULT 'STARTED',
  result JSON NULL,
  validation_errors JSON NULL,
  error_category VARCHAR(80) NULL,
  safe_error JSON NULL,
  started_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  duration_ms INT UNSIGNED NULL,
  PRIMARY KEY (id),
  KEY idx_mcp_started (started_at, id),
  KEY idx_mcp_actor (hr_user_id, started_at),
  KEY idx_mcp_tool (tool_name, started_at),
  CONSTRAINT fk_mcp_tool_user FOREIGN KEY (hr_user_id) REFERENCES hr_users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT chk_mcp_tool_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE ai_trace_reviews (
  trace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reviewer_hr_user_id INT UNSIGNED NOT NULL,
  verdict ENUM('CORRECT','PARTIAL','INCORRECT') NOT NULL,
  note VARCHAR(2000) NOT NULL,
  nominated BOOLEAN NOT NULL DEFAULT FALSE,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (trace_id),
  KEY idx_ai_reviews_reviewer (reviewer_hr_user_id, updated_at),
  CONSTRAINT fk_ai_reviews_trace FOREIGN KEY (trace_id) REFERENCES ai_traces(id) ON UPDATE RESTRICT ON DELETE CASCADE,
  CONSTRAINT fk_ai_reviews_user FOREIGN KEY (reviewer_hr_user_id) REFERENCES hr_users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT chk_ai_reviews_version CHECK (version >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
